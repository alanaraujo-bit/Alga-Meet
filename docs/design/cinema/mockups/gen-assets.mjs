// Renders the real Eco master drawing and the app's Phosphor icons to static SVG strings (assets.js) for the mockups.
// Run from the repo root: node docs/design/cinema/mockups/gen-assets.mjs
import { build } from 'esbuild'
import { writeFileSync, mkdtempSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const ICONS = [
  'Microphone', 'Headphones', 'MonitorArrowUp', 'ProjectorScreen', 'SlidersHorizontal', 'PhoneDisconnect', 'SpeakerHigh',
  'Play', 'Pause', 'ArrowCounterClockwise', 'ArrowClockwise', 'Subtitles', 'CornersOut', 'Smiley', 'DotsThree',
  'PencilSimple', 'DownloadSimple', 'Copy', 'Warning', 'Check', 'CaretDown', 'SignOut', 'UsersThree', 'ChatCircle',
  'MagnifyingGlass', 'Hash', 'LockSimple', 'Plus', 'X', 'Info', 'ArrowLeft', 'FilmSlate', 'Armchair', 'GearSix',
]
const entry = `
import { renderToStaticMarkup as r } from 'react-dom/server'
import { createElement as h } from 'react'
import { Eco } from '../../../../apps/desktop/src/renderer/src/ui/eco/Eco'
import { BRAND_ECO } from '../../../../apps/desktop/src/renderer/src/ui/eco/ecoRules'
import * as P from '@phosphor-icons/react/dist/ssr'
const PEOPLE = {
  ana:   { accent: '#f07a9a', eyes: 'almond', hair: 'wavy', accessory: 'none' },
  pedro: { accent: '#5b8bd6', eyes: 'bar', hair: 'none', accessory: 'headset' },
  bia:   { accent: '#b9a6f5', eyes: 'wing', hair: 'buns', accessory: 'none' },
  lucas: { accent: '#f5a524', eyes: 'dot', hair: 'none', accessory: 'beanie' },
}
const out = { eco: {}, avatar: {}, accent: {}, icon: {} }
for (const [k, spec] of Object.entries(PEOPLE)) {
  out.accent[k] = spec.accent
  for (const size of [64, 32, 20]) out.avatar[k + size] = r(h(Eco, { spec, framing: 'avatar', size }))
}
out.eco.idle = r(h(Eco, { spec: BRAND_ECO, state: 'idle', size: 130 }))
out.eco.listening = r(h(Eco, { spec: BRAND_ECO, state: 'listening', size: 130 }))
for (const n of ${JSON.stringify(ICONS)}) for (const w of ['regular', 'bold', 'fill']) out.icon[n + (w === 'regular' ? '' : '.' + w)] = r(h(P[n], { size: 20, weight: w }))
process.stdout.write(JSON.stringify(out))
`
const dir = mkdtempSync(join(tmpdir(), 'cinema-assets-'))
const outfile = join(dir, 'bundle.cjs')
await build({
  stdin: { contents: entry, resolveDir: here, loader: 'tsx' },
  bundle: true, platform: 'node', format: 'cjs', outfile, jsx: 'automatic',
  loader: { '.css': 'local-css' }, logLevel: 'error',
})
const { execFileSync } = await import('node:child_process')
const json = execFileSync(process.execPath, [outfile], { maxBuffer: 64 << 20 }).toString()
writeFileSync(join(here, 'assets.js'), `// Generated by gen-assets.mjs: the real Eco and the app's Phosphor icons as static SVG.\nwindow.A = ${json}\n`)
console.log('assets.js', (json.length / 1024).toFixed(0), 'KiB')
