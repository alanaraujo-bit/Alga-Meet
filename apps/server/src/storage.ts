/** Object storage for uploads: local disk (dev, or a mounted volume) or any S3-compatible bucket (SigV4 via aws4fetch). */
import { createReadStream, openAsBlob } from 'node:fs'
import { copyFile, mkdir, rename, rm, stat } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { Readable } from 'node:stream'
import { AwsClient } from 'aws4fetch'
import type { StorageConfig } from './config.js'

export interface PutInfo {
  size: number
  /** Hex SHA-256 of the bytes; S3 verifies it on PUT. */
  sha256: string
  contentType: string
}

/** Inclusive byte range. */
export interface ByteRange {
  start: number
  end: number
}

export interface Storage {
  /** Stores the file at `path` under `key` (the temp file may be moved). */
  put(key: string, path: string, info: PutInfo): Promise<void>
  /** The object's bytes, or null when it does not exist. */
  get(key: string, range?: ByteRange): Promise<Readable | null>
  /** Idempotent: deleting a missing object succeeds. */
  delete(key: string): Promise<void>
}

// Keys are generated by the server ("attachments/<channel>/<id>", "avatars/<user>/<hex>.png"): never user text, no "..".
const KEY_RE = /^[a-z]+(?:\/[A-Za-z0-9_-][A-Za-z0-9._-]*)+$/
function checkKey(key: string): string {
  if (!KEY_RE.test(key)) throw new Error(`invalid storage key: ${key}`)
  return key
}

export class LocalStorage implements Storage {
  constructor(private readonly root: string) {}

  private file(key: string): string {
    return join(this.root, ...checkKey(key).split('/'))
  }

  async put(key: string, path: string): Promise<void> {
    const dest = this.file(key)
    await mkdir(dirname(dest), { recursive: true })
    try {
      await rename(path, dest)
    } catch (err) {
      if ((err as NodeJS.ErrnoException).code !== 'EXDEV') throw err
      await copyFile(path, dest) // temp dir on another volume
    }
  }

  async get(key: string, range?: ByteRange): Promise<Readable | null> {
    const file = this.file(key)
    try {
      await stat(file)
    } catch (err) {
      if ((err as NodeJS.ErrnoException).code === 'ENOENT') return null
      throw err
    }
    return createReadStream(file, range ?? {})
  }

  async delete(key: string): Promise<void> {
    await rm(this.file(key), { force: true })
  }
}

export class S3Storage implements Storage {
  private readonly client: AwsClient

  constructor(private readonly cfg: Extract<StorageConfig, { driver: 's3' }>) {
    // Retries re-sign and resend the request; bodies are Blobs (re-readable), so that is safe for PUT too.
    this.client = new AwsClient({ accessKeyId: cfg.accessKeyId, secretAccessKey: cfg.secretAccessKey, service: 's3', region: cfg.region, retries: 2 })
  }

  private url(key: string): string {
    const e = new URL(this.cfg.endpoint)
    const base = e.pathname.replace(/\/+$/, '')
    return this.cfg.pathStyle
      ? `${e.origin}${base}/${this.cfg.bucket}/${checkKey(key)}`
      : `${e.protocol}//${this.cfg.bucket}.${e.host}${base}/${checkKey(key)}`
  }

  async put(key: string, path: string, info: PutInfo): Promise<void> {
    // A file-backed Blob streams from disk with a known Content-Length (S3 refuses chunked PUTs).
    const body = await openAsBlob(path)
    const res = await this.client.fetch(this.url(key), {
      method: 'PUT',
      body,
      headers: { 'content-type': info.contentType, 'x-amz-content-sha256': info.sha256 },
    })
    if (!res.ok) throw new Error(`S3 PUT ${key} failed: ${res.status} ${(await res.text()).slice(0, 200)}`)
  }

  async get(key: string, range?: ByteRange): Promise<Readable | null> {
    const res = await this.client.fetch(this.url(key), {
      headers: range ? { range: `bytes=${range.start}-${range.end}` } : {},
    })
    if (res.status === 404) {
      await res.body?.cancel()
      return null
    }
    if (!res.ok || !res.body) throw new Error(`S3 GET ${key} failed: ${res.status} ${(await res.text()).slice(0, 200)}`)
    return Readable.fromWeb(res.body as import('node:stream/web').ReadableStream)
  }

  async delete(key: string): Promise<void> {
    const res = await this.client.fetch(this.url(key), { method: 'DELETE' })
    await res.body?.cancel()
    if (!res.ok && res.status !== 404) throw new Error(`S3 DELETE ${key} failed: ${res.status}`)
  }
}

export function createStorage(cfg: StorageConfig): Storage {
  return cfg.driver === 's3' ? new S3Storage(cfg) : new LocalStorage(cfg.dir)
}
