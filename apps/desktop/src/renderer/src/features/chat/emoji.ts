/** Strips accents and lowercases, so "coração" finds "coracao". */
const fold = (s: string) => s.normalize('NFD').replace(/\p{M}/gu, '').toLowerCase()

export function searchEmoji(q: string): string[] {
  const needle = fold(q.trim())
  if (!needle) return EMOJI.map(([e]) => e)
  return EMOJI.filter(([, k]) => fold(k).split(' ').some((w) => w.startsWith(needle)) || fold(k).includes(needle)).map(([e]) => e)
}
